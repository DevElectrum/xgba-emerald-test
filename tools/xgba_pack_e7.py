#!/usr/bin/env python3
"""E7: verified sparse 256 MiB ROM with real geometry at five remote addresses."""

import argparse
import struct
import zlib
from pathlib import Path
import xgba_pack_e3 as e3
import xgba_generate_e3 as g

ROOT = Path(__file__).resolve().parent.parent
HEADER = ROOT / "include/xgba_e7_data.h"
ROM_SIZE = 0x10000000
STRIDE = 0x00100000
REMOTE_WORLDS = {
    3: 0x04000000,
    6: 0x08000000,
    10: 0x0C000000,
    14: 0x0E000000,
    20: 0x0FF00000,
}
MARKER_MAGIC = b"XGBAE7!!"
MARKER_SIZE = 16


def world_base(world):
    if world < 3 or world > 20:
        raise ValueError("E7 world outside 3..20")
    return REMOTE_WORLDS.get(world, g.FIRST_OFFSET + (world - 3) * STRIDE)


def marker(world):
    offset = world_base(world) + STRIDE - MARKER_SIZE
    prefix = MARKER_MAGIC + struct.pack("<I", offset)
    return offset, prefix + struct.pack("<I", zlib.crc32(prefix))


def render_header():
    lines = [
        "#ifndef GUARD_XGBA_E7_DATA_H", "#define GUARD_XGBA_E7_DATA_H", "",
        "// Generated by tools/xgba_pack_e7.py generate. Do not hand-edit.",
        "#define XGBA_E7_ROM_SIZE 0x10000000u",
        "#define XGBA_E7_PROBE_COUNT 5", "",
        "static const u32 sXgbaE7WorldBases[18] =", "{",
    ]
    for world in range(3, 21):
        lines.append(f"    0x{world_base(world):08X}u, // World {world}")
    lines += ["};", "", "static const u32 sXgbaE7ProbeOffsets[XGBA_E7_PROBE_COUNT] =", "{"]
    for world in REMOTE_WORLDS:
        offset, _ = marker(world)
        lines.append(f"    0x{offset:08X}u, // World {world}")
    lines += ["};", "", "static const u8 sXgbaE7ProbeBytes[XGBA_E7_PROBE_COUNT][16] =", "{"]
    for world in REMOTE_WORLDS:
        _, data = marker(world)
        lines.append("    { " + ", ".join(f"0x{byte:02X}" for byte in data) + " },")
    lines += ["};", "", "#endif", ""]
    return "\n".join(lines)


def validate_intervals(regions):
    previous_end = 0
    for offset, size, name in sorted(regions):
        if offset < 0 or size < 1 or offset + size > ROM_SIZE:
            raise ValueError(f"Out of bounds ROM asset {name}: {offset:#x} + {size:#x}")
        if offset < previous_end:
            raise ValueError(f"Overlapping ROM asset {name} at {offset:#x}")
        previous_end = offset + size


def layout_plan(args):
    prefix, old_payloads, _ = e3.plan(args)
    placed = []
    bounds = [(0, len(prefix), "Emerald source and base assets")]
    first = g.FIRST_OFFSET
    last = first + 18 * STRIDE

    for index, (offset, data) in enumerate(old_payloads):
        if first <= offset < last:
            world = 3 + (offset - first) // STRIDE
            relative = (offset - first) % STRIDE
            if world in REMOTE_WORLDS and relative + len(data) > STRIDE - MARKER_SIZE:
                raise ValueError(f"World {world} geometry overlaps its marker")
            offset = world_base(world) + relative
        placed.append((offset, data))
        bounds.append((offset, len(data), f"asset {index}"))

    for world in REMOTE_WORLDS:
        offset, data = marker(world)
        placed.append((offset, data))
        bounds.append((offset, len(data), f"World {world} marker"))

    validate_intervals(bounds)
    if HEADER.read_text() != render_header():
        raise ValueError("E7 C addresses differ from packer; run generate")
    return prefix, placed


def verify(args):
    prefix, placed = layout_plan(args)
    rom = Path(args.output)
    if rom.stat().st_size != ROM_SIZE:
        raise ValueError(f"E7 ROM must be exactly {ROM_SIZE} bytes")
    if prefix[0xB5:0xBC] != b"XGBA256" or prefix[0xBC] != 0xE6:
        raise ValueError("E7 must preserve E6 save-format header revision")
    with rom.open("rb") as f:
        if f.read(len(prefix)) != prefix:
            raise ValueError("Base ROM/header differs")
        for offset, data in placed:
            f.seek(offset)
            if f.read(len(data)) != data:
                raise ValueError(f"E7 mismatch at ROM offset {offset:#x}")
    print(f"E7 VERIFIED: 256 MiB, 20 worlds, {len(placed)} asset/marker placements")
    print("  live map geometry at 64, 128, 192, 224 and 255 MiB; last byte checked")


def pack(args):
    output = Path(args.output)
    if output.resolve() == Path(args.rom).resolve():
        raise ValueError("Cannot replace Emerald source ROM")
    prefix, placed = layout_plan(args)
    with output.open("xb") as f:
        f.write(prefix)
        for offset, data in placed:
            f.seek(offset)
            f.write(data)
        f.truncate(ROM_SIZE)
    verify(args)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=("pack", "verify", "generate", "check-header"))
    parser.add_argument("--rom", default="pokeemerald.gba")
    parser.add_argument("--output", default="xgba-emerald-e7.gba")
    parser.add_argument("--elf", default="pokeemerald.elf")
    parser.add_argument("--nm", default="arm-none-eabi-nm")
    args = parser.parse_args()
    args.e6_save = True
    args.e5_save = False

    if args.command == "generate":
        result = render_header()
        if not HEADER.exists() or HEADER.read_text() != result:
            HEADER.write_text(result)
        print("E7 high-address header generated")
    elif args.command == "check-header":
        if HEADER.read_text() != render_header():
            raise ValueError("E7 C world mapping drift")
        print("E7 high-address header parity PASS")
    elif args.command == "pack":
        pack(args)
    else:
        verify(args)


if __name__ == "__main__":
    main()
